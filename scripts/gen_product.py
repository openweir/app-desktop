"""Generate the Go product identifiers from product.json (docs/decisions.md D49).

    uv run python scripts/gen_product.py          # write src/core/internal/product/product_gen.go
    uv run python scripts/gen_product.py --check  # exit 1 if the file is stale

The Go module cannot embed a file outside src/core, so the identifiers are generated, like
Theme.qml from DESIGN.md. The signing identities are variables: a signed release links them in
with -X from the release environment (scripts/build_windows.py), as it does Version; so is the
Linux update key (OPENWEIR_LINUX_UPDATE_KEY, D62).
"""

from __future__ import annotations

import argparse
import json
import posixpath
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "product.json"
OUTPUT = ROOT / "src" / "core" / "internal" / "product" / "product_gen.go"


def go_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def go_int(value: object) -> str:
    if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
        raise ValueError(f"expected a positive integer, not {value!r}")
    return str(value)


def render(data: dict) -> str:
    windows = data["windows"]
    linux = data["linux"]
    signing = data["signing"]
    pipe = rf"\\.\pipe\ProtectedPrefix\Administrators\{data['productId']}"
    install = linux["installDir"]
    return f"""// Code generated by scripts/gen_product.py from product.json. DO NOT EDIT.

package product

const (
	// DisplayName also names the data directories (docs/architecture.md §5.1).
	DisplayName = {go_string(data["displayName"])}

	ServiceName = {go_string(windows["serviceName"])}

	// UIExecutable is the only client the Windows service accepts, from its own directory.
	UIExecutable = {go_string(windows["uiExecutable"])}

	PipeName = `{pipe}`
)

// The Linux package's identifiers (docs/architecture.md "Linux", D60 to D67). The
// service, LinuxServicePath, runs as the systemd units <LinuxUnit>.service and
// <LinuxUnit>.socket, which listens on LinuxSocket; the only client it accepts is LinuxUIPath.
const (
	LinuxInstallDir        = {go_string(install)}
	LinuxUIExecutable      = {go_string(linux["uiExecutable"])}
	LinuxServiceExecutable = {go_string(linux["serviceExecutable"])}
	LinuxUIPath            = {go_string(posixpath.join(install, linux["uiExecutable"]))}
	LinuxServicePath       = {go_string(posixpath.join(install, linux["serviceExecutable"]))}
	LinuxUnit              = {go_string(linux["unit"])}
	LinuxSocket            = {go_string(linux["socket"])}
	// LinuxStateDir is the service's root, systemd's StateDirectory.
	LinuxStateDir  = {go_string(linux["stateDir"])}
	LinuxDesktopID = {go_string(linux["desktopId"])}

	// The TUN the Linux service owns, and the policy routing table and rule priorities its
	// auto-route writes, from LinuxRuleIndex to LinuxRuleIndex+10. The service holds every
	// profile to them, and its cleanup removes exactly them after a crash (D67), so they
	// must be no one else's: not mihomo's and sing-box's defaults (table 2022, rules from
	// 9000), Tailscale's (52, 5210-5270), strongSwan's (220), wg-quick's (51820) or the
	// kernel's (253-255; rules 0, 32766, 32767).
	LinuxTunDevice  = {go_string(linux["tunDevice"])}
	LinuxRouteTable = {go_int(linux["routeTable"])}
	LinuxRuleIndex  = {go_int(linux["ruleIndex"])}
)

// WindowsSigner and WindowsSignerEKU name the Authenticode signer that a service linked with
// SignedRelease requires of the UI (docs/architecture.md §5.3): the display name of the
// certificate's subject and an extended key usage only OpenWeir's certificate profile has.
// product.json leaves them empty; a signed release sets them at link time.
var (
	WindowsSigner    = {go_string(signing["windowsSigner"])}
	WindowsSignerEKU = {go_string(signing["windowsSignerEku"])}
)

// LinuxUpdateKey is the Ed25519 public key that checks a Linux release's SHA256SUMS.sig (D62):
// the update helper installs no package without it. product.json leaves it empty, and a build
// without OPENWEIR_LINUX_UPDATE_KEY offers no installer; a release sets it at link time.
var LinuxUpdateKey = {go_string(signing["linuxUpdateKey"])}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    arguments = parser.parse_args()
    expected = render(json.loads(SOURCE.read_text("utf-8")))
    if arguments.check:
        current = OUTPUT.read_text("utf-8") if OUTPUT.exists() else ""
        if current != expected:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run scripts/gen_product.py")
            return 1
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
